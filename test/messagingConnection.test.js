'use strict';
process.env.VMTL_DB = ':memory:';
delete process.env.DB_RUNTIME;
const { test } = require('node:test');
const assert = require('node:assert/strict');
const settings = require('../src/services/settings');
const connection = require('../src/services/messagingConnection');
const email = require('../src/services/email');
const sms = require('../src/services/sms');

test('Tekmail and mNotify use saved settings, test while off, and require successful current tests to activate', async t => {
  const original = global.fetch; t.after(() => { global.fetch = original; });
  const requests = [];
  let response = { success: true };
  global.fetch = async (url, init) => { requests.push({ url: String(url), init }); return { ok: true, status: 200, json: async () => response }; };
  await connection.save('email', { api_url: email.DEFAULT_API_URL, app_id: 'VMTL test', channel: 'VMTL', api_key: ' private-email-key ' });
  assert.equal((await connection.status('email')).status.state, 'needs_test');
  assert.doesNotMatch(JSON.stringify(await connection.status('email')), /private-email-key/);
  await assert.rejects(connection.activate('email', true), /successful test/);
  assert.equal((await email.send('person@example.test', 'Subject', 'Body')).ok, false);
  const cfg = await connection.config('email');
  const result = await email.send('person@example.test', 'Subject', 'Body', { force: true, hub: true });
  assert.equal(result.ok, true);
  assert.equal(requests[0].init.headers['X-API-KEY'], 'private-email-key');
  const payload = JSON.parse(requests[0].init.body);
  assert.equal(payload.appId, 'VMTL test'); assert.equal(payload.channel, 'VMTL');
  assert.deepEqual(payload.recipients, ['person@example.test']); assert.equal(payload.body.contentType, 'html'); assert.match(payload.body.content, /Body/);
  await connection.recordTest('email', cfg, 'person@example.test', result);
  assert.equal((await connection.activate('email', true)).status.state, 'active');
  assert.equal((await connection.activate('email', false)).status.enabled, false);
  await connection.save('email', { api_key: '', channel: 'CHANGED' });
  assert.equal((await connection.config('email')).api_key, 'private-email-key');
  await assert.rejects(connection.activate('email', true), /successful test/);
  response = { success: false };
  assert.equal((await email.send('person@example.test', 'Subject', 'Body', { force: true })).ok, false);
  await connection.save('sms', { api_key: 'private-sms-key', sender_id: 'VMTL', api_url: 'https://api.mnotify.com/api/sms/quick' });
  assert.equal((await sms.send('0244000000', 'Test')).ok, false);
  response = { code: '2000', status: 'success' };
  const smsCfg = await connection.config('sms');
  const smsResult = await sms.send('0244000000', 'Test', { force: true });
  assert.equal(smsResult.ok, true);
  const sent = requests.at(-1); assert.equal(new URL(sent.url).searchParams.get('key'), 'private-sms-key');
  assert.deepEqual(JSON.parse(sent.init.body).recipient, ['233244000000']);
  await connection.recordTest('sms', smsCfg, '0244000000', smsResult);
  assert.equal((await connection.activate('sms', true)).status.state, 'active');
  response = { code: '4000', status: 'error' };
  assert.equal((await sms.send('0244000000', 'Test', { force: true })).ok, false);
  await connection.save('sms', { clear_key: true });
  assert.equal((await connection.status('sms')).status.configured, false);
  await assert.rejects(connection.save('email', { api_url: 'http://example.test', app_id: 'Must not save' }), /HTTPS/);
  assert.equal(await settings.get('mail_app_id'), 'VMTL test');
  await assert.rejects(connection.save('sms', { sender_id: 'too-long-sender-id' }), /1–11/);
});

test('connection routes are protected and never return the saved key', async t => {
  const db = require('../src/db/sqlite');
  db.exec("INSERT INTO users(id,name,email,password_hash,is_super_admin) VALUES(1,'Owner','owner@test','x',1),(2,'Staff','staff@test','x',0)");
  const express = require('express'); const app = require('../src/middleware/asyncSafe').asyncSafe(express());
  app.use(express.json()); app.use((req, res, next) => { req.session = { user: db.prepare('SELECT * FROM users WHERE id=?').get(Number(req.headers['x-test-user'] || 0)) }; next(); });
  require('../src/routes/api/admin')(app); app.use(require('../src/middleware/errorHandler'));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve)); t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/admin/messaging/email`;
  assert.equal((await fetch(base + '/connection')).status, 401);
  assert.equal((await fetch(base + '/connection', { headers: { 'x-test-user': '2' } })).status, 403);
  const result = await fetch(base + '/connection', { headers: { 'x-test-user': '1' } });
  assert.equal(result.status, 200); assert.equal(result.headers.get('cache-control'), 'no-store');
  assert.doesNotMatch(await result.text(), /private-email-key/);
});
